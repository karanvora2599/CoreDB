def test_pagerank_over_the_whole_graph_is_a_distribution(meridian):
    """PageRank's defining invariant: every active entity gets a positive
    score and the scores sum to 1. Cheap enough to keep in the default run,
    and it exercises `_active_entity_ids`' full-table scan at 64k versions."""
    on_date = meridian.gt("hub")["on_date"]
    scores = meridian.db.pagerank_all(on_date)

    assert len(scores) > 4_000
    assert sum(scores.values()) == pytest.approx(1.0)
    assert min(scores.values()) > 0.0
    assert meridian.gt("hub")["entity"] in scores


@pytest.mark.deep
def test_betweenness_over_the_whole_graph_ranks_the_planted_hub_highly(meridian):
    """Every one of the hub's peers reaches every other only through it, so
    the hub carries all those shortest paths - it should sit far above the
    median. A ranking claim, not an exact score: `max_depth` bounds the
    search, so the absolute number is depth-dependent by design."""
    hub = meridian.gt("hub")
    scores = meridian.db.betweenness_all(hub["on_date"], max_depth=3)

    ranked = sorted(scores.values(), reverse=True)
    assert scores[hub["entity"]] > 0.0
    assert scores[hub["entity"]] >= ranked[len(ranked) // 100], "not in the top percentile"


@pytest.mark.deep
def test_dump_restore_round_trips_every_fact(meridian, tmp_path):
    """`facts.jsonl` is `Database.dump()`'s output, and `coredb.restore()`
    is the documented migration path across a schema change. Round-tripping
    the whole dataset is the only way to know that path holds at scale - it
    replays ~64k intervals through the public write API."""
    import coredb

    facts = meridian.path / meridian.manifest["files"]["facts"]
    restored_path = tmp_path / "restored.db"
    restored = coredb.restore(str(facts), str(restored_path), map_size=4 << 30)
    try:
        assert restored.stats()["versions"] == meridian.manifest["stats"]["versions"]
        round_tripped = tmp_path / "round_tripped.jsonl"
        restored.dump(str(round_tripped))
    finally:
        restored.close()

    def records(path):
        with open(path, encoding="utf-8") as f:
            return sorted(tuple(sorted(json.loads(line).items())) for line in f if line.strip())

    assert records(round_tripped) == records(facts)
