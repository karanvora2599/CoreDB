def test_history_returns_every_planted_churn_interval(meridian):
    """One triple opened and closed repeatedly. `HISTORY` must return every
    interval, in order, with exact boundaries - a relationship that reopens
    is a new version, never an edit of the previous one."""
    churn = meridian.gt("churn")
    subject, predicate, obj = churn["triple"]
    versions = meridian.db.history((subject, predicate, obj))

    assert len(versions) == churn["n_versions"]
    assert [[v.valid_from, v.valid_to] for v in versions] == churn["intervals"]
    assert len({v.relationship_id for v in versions}) == 1, "one relationship, many versions"


def test_why_changed_surfaces_every_planted_citation(meridian):
    """Each open cited exactly one source. Over the whole window the status
    is `churned` and the evidence trail must contain every one of those
    citations, each resolved to its source."""
    churn = meridian.gt("churn")
    subject, predicate, obj = churn["triple"]
    window_start = churn["intervals"][0][0]
    window_end = churn["intervals"][-1][1]

    result = meridian.db.why_changed(subject, predicate, obj, window_start, window_end)

    assert result["status"] == churn["expected_status"]
    assert len(result["assertions"]) == churn["n_assertions_in_window"]
    assert all(entry["source"] is not None for entry in result["assertions"])
    assert [entry["source"]["url"] for entry in result["assertions"]] == churn["source_urls"]


def test_as_known_respects_the_system_time_axis(meridian):
    """Bitemporality's whole point: asking for a past valid-time date with a
    knowledge cutoff before anything was recorded must return nothing, while
    the same date with a present-day cutoff returns the facts."""
    hub = meridian.gt("hub")
    pattern = (hub["entity"], None, None)

    assert meridian.db.as_of(pattern, hub["on_date"])
    assert meridian.db.as_known(pattern, hub["on_date"], "2000-01-01") == []
    assert len(meridian.db.as_known(pattern, hub["on_date"], "2100-01-01")) == hub["degree"]


