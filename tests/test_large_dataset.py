# Fast-path equivalence, at a history depth small fixtures cannot reach
# ----------------------------------------------------------------------

_ORACLE_WINDOW = ("2023-01-01", "2023-04-30")


def test_track_degree_sweep_matches_per_date_oracle_at_scale(meridian):
    """`track()` sweeps intervals once, O(H + D); `degree()` rebuilds the
    neighbour set per date, O(H) each. On an entity with hundreds of
    intervals the two must still agree exactly."""
    entity = meridian.gt("deep_history")["entities"][0]
    assert len(meridian.db.history((entity, None, None))) > 200, "not a deep-history entity"

    dates = list(date_range(*_ORACLE_WINDOW))
    expected = [(d, meridian.db.degree(entity, d)) for d in dates]
    assert meridian.db.track("degree", entity, *_ORACLE_WINDOW).points == expected


def test_track_weighted_degree_sweep_matches_per_date_oracle_at_scale(meridian):
    """Same equivalence for the weighted form, compared approximately: the
    sweep accumulates running +=/-= adjustments while `degree()` re-sums
    from scratch, and float addition is not associative - over hundreds of
    intervals those orderings genuinely differ in the last bits."""
    entity = meridian.gt("deep_history")["entities"][0]
    dates = list(date_range(*_ORACLE_WINDOW))
    expected = [(d, meridian.db.degree(entity, d, weighted=True)) for d in dates]
    actual = meridian.db.track("weighted_degree", entity, *_ORACLE_WINDOW).points

    assert [d for d, _ in actual] == [d for d, _ in expected]
    for (_, got), (_, want) in zip(actual, expected):
        assert got == pytest.approx(want)


def test_series_iteration_matches_per_date_as_of_at_scale(meridian):
    """`SERIES` iteration is the same sweep applied to whole snapshots
    rather than a scalar; `as_of()` per date is the oracle."""
    entity = meridian.gt("deep_history")["entities"][0]
    pattern = (entity, "SUPPLIES", None)
    series = meridian.db.series(pattern, *_ORACLE_WINDOW, resolution_days=1)

    swept = {d: sorted(v.version_id for v in snapshot) for d, snapshot in series}
    per_date = {d: sorted(v.version_id for v in meridian.db.as_of(pattern, d))
                for d in date_range(*_ORACLE_WINDOW)}
    assert swept == per_date


