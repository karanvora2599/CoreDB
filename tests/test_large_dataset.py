def test_tgql_match_applies_where_and_limit(meridian):
    hub = meridian.gt("hub")
    entity, on_date, degree = hub["entity"], hub["on_date"], hub["degree"]

    everything = meridian.db.execute(f"MATCH ({entity}, ?p, ?o) AS OF '{on_date}'")
    assert len(everything) == degree

    limited = meridian.db.execute(f"MATCH ({entity}, ?p, ?o) AS OF '{on_date}' LIMIT 10")
    assert len(limited) == 10

    # Every planted peer carries the same confidence, so the two filters
    # bracket it: one keeps all of them, the other none.
    confidence = everything[0]["confidence"]
    kept = meridian.db.execute(
        f"MATCH ({entity}, ?p, ?o) AS OF '{on_date}' WHERE confidence >= {confidence}")
    dropped = meridian.db.execute(
        f"MATCH ({entity}, ?p, ?o) AS OF '{on_date}' WHERE confidence > {confidence}")
    assert len(kept) == degree
    assert dropped == []


def test_tgql_history_matches_the_python_api(meridian):
    subject, predicate, obj = meridian.gt("churn")["triple"]
    rows = meridian.db.execute(f"HISTORY ({subject}, {predicate}, {obj})")
    assert len(rows) == meridian.gt("churn")["n_versions"]
    assert [r["valid_from"] for r in rows] == [i[0] for i in meridian.gt("churn")["intervals"]]


def test_tgql_diff_reports_the_planted_regime_boundary(meridian):
    """Crossing a regime boundary opens exactly the difference between the
    two regimes' target degrees, and closes nothing (the previous regime's
    edges stay open); the later boundary closes the difference instead."""
    shift = meridian.gt("shift")
    entity = shift["entity"]
    (_, first), (second_start, second), (third_start, third) = shift["regimes"]

    opening = meridian.db.execute(
        f"DIFF BETWEEN '2023-07-02' AND '{second_start}' FOR ({entity}, ?p, ?o)")
    assert len(opening["edges_opened"]) == second - first
    assert opening["edges_closed"] == []

    closing = meridian.db.execute(
        f"DIFF BETWEEN '2024-10-05' AND '{third_start}' FOR ({entity}, ?p, ?o)")
    assert len(closing["edges_closed"]) == second - third
    assert closing["edges_opened"] == []


def test_tgql_series_and_track_agree_on_the_planted_regimes(meridian):
    shift = meridian.gt("shift")
    entity, (start, end) = shift["entity"], shift["window"]
    resolution = f"{shift['resolution_days']}d"

    series = meridian.db.execute(
        f"SERIES ({entity}, ?p, ?o) BETWEEN '{start}' AND '{end}' RESOLUTION '{resolution}'")
    track = meridian.db.execute(
        f"TRACK DEGREE({entity}) BETWEEN '{start}' AND '{end}' RESOLUTION '{resolution}'")

    assert [len(row["facts"]) for row in series] == [point["value"] for point in track]


def test_tgql_changepoints_find_the_planted_regime_boundaries(meridian):
    shift = meridian.gt("shift")
    entity, (start, end) = shift["entity"], shift["window"]
    result = meridian.db.execute(
        f"CHANGEPOINTS DEGREE({entity}) BETWEEN '{start}' AND '{end}' "
        f"RESOLUTION '{shift['resolution_days']}d'")
    assert result["changepoints"] == shift["expected_changepoints"]


def test_tgql_path_and_first_connected_match_the_planted_chain(meridian):
    chain = meridian.gt("chain")
    start, end = chain["nodes"][0], chain["nodes"][-1]
    connected_date = chain["first_connected"]
    window = chain["first_connected_window"]

    path = meridian.db.execute(f"PATH ({start}, {end}) AS OF '{connected_date}' MAX_DEPTH 4")
    assert path["connected"] is True
    assert len(path["path"]) == chain["expected_hops"]

    first = meridian.db.execute(
        f"FIRST_CONNECTED ({start}, {end}) BETWEEN '{window[0]}' AND '{window[1]}' MAX_DEPTH 4")
    assert first["first_connected"] == connected_date


def test_tgql_why_changed_returns_the_planted_evidence(meridian):
    churn = meridian.gt("churn")
    subject, predicate, obj = churn["triple"]
    start, end = churn["intervals"][0][0], churn["intervals"][-1][1]

    result = meridian.db.execute(
        f"WHY_CHANGED ({subject}, {predicate}, {obj}) BETWEEN '{start}' AND '{end}'")
    assert result["status"] == churn["expected_status"]
    assert len(result["assertions"]) == churn["n_assertions_in_window"]


