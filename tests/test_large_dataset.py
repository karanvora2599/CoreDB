"""CoreDB exercised against the Meridian dataset - ~64k relationship
versions over a five-year calendar, generated by `tools/gen_test_dataset.py`
outside the repository.

The rest of the suite works on graphs of a dozen edges built inline, which is
right for pinning down semantics but says nothing about behaviour at a scale
where a full table scan costs real time and an entity's history is hundreds
of intervals deep. These tests cover three things that only show up there:

1. **Planted ground truth.** `tools/dataset_spec.py` builds the ingestion log
   without importing `coredb` at all, and records what it planted - hop
   counts, regime boundaries, churn intervals, citations - in the manifest.
   Checking the engine against that is a real oracle, not the engine
   agreeing with itself.
2. **Fast-path equivalence at a scale that matters.** `TRACK`'s O(H + D)
   sweep and the native change-point search have per-date/pure-Python
   equivalents that are obviously correct and too slow to ship. At H in the
   hundreds they can finally disagree in ways a six-edge fixture cannot
   provoke.
3. **The TGQL surface end to end**, against a database large enough that a
   wrong index choice shows up as a wrong answer rather than a fast one.

Every test skips cleanly when the dataset is absent - see `conftest.py`'s
`meridian` fixture. `--deep` adds the whole-graph tests (global centrality,
a full dump/restore round-trip) that are too slow for a routine run.
"""
import hashlib
import json
from pathlib import Path

import pytest

from coredb.series import date_range
from coredb.signal import detect_changepoints


# ----------------------------------------------------------------------
# Dataset integrity - is the thing we are testing against the thing the
# current checkout's spec describes?
# ----------------------------------------------------------------------

def test_events_file_matches_its_recorded_checksum(meridian_manifest):
    path = Path(meridian_manifest["_dir"])
    digest = hashlib.sha256()
    with open(path / meridian_manifest["files"]["events"], "rb") as f:
        for line in f:
            digest.update(line)
    assert digest.hexdigest() == meridian_manifest["events"]["sha256"]


def test_regenerating_the_spec_reproduces_the_shipped_log(meridian_manifest):
    """The generator claims byte-reproducibility from (spec_version, scale,
    seed). Rebuilding the log in-process and hashing it the same way is what
    makes that claim testable - and is what catches a dataset built from an
    older spec, or a spec that has quietly stopped being deterministic (a
    single unsorted set iteration is enough to do that)."""
    from tools.dataset_spec import build_events

    events, _ = build_events(scale=meridian_manifest["scale"], seed=meridian_manifest["seed"])
    digest = hashlib.sha256()
    for event in events:
        digest.update((json.dumps(event, separators=(",", ":"), sort_keys=True) + "\n").encode())

    assert len(events) == meridian_manifest["events"]["count"]
    assert digest.hexdigest() == meridian_manifest["events"]["sha256"]


def test_engine_stats_match_the_manifest(meridian):
    """Not an independent oracle - `stats` was written by asking the engine
    at build time. It is a regression signal: the same log must still
    produce the same shape."""
    assert meridian.db.stats() == meridian.manifest["stats"]


def test_dataset_is_large_enough_to_be_worth_testing_on(meridian):
    stats = meridian.db.stats()
    assert stats["versions"] >= 50_000
    assert stats["relationships"] >= 50_000
    assert stats["entities"] >= 4_000
    assert stats["assertions"] >= 10_000


