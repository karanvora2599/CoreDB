def test_degree_is_flat_inside_each_planted_regime(meridian):
    """The shift entity's degree is a step function by construction: every
    weekly sample inside a regime must equal that regime's target exactly,
    which is what makes the change-point expectation below exact rather than
    approximate."""
    shift = meridian.gt("shift")
    signal = meridian.db.track("degree", shift["entity"], shift["window"][0], shift["window"][1],
                                shift["resolution_days"])
    by_date = dict(signal.points)
    regimes = shift["regimes"]

    for i, (regime_start, target) in enumerate(regimes):
        regime_end = regimes[i + 1][0] if i + 1 < len(regimes) else shift["window"][1]
        sampled = [d for d in by_date if regime_start <= d < regime_end] if i + 1 < len(regimes) \
            else [d for d in by_date if regime_start <= d <= regime_end]
        assert sampled, f"no samples in regime starting {regime_start}"
        assert {by_date[d] for d in sampled} == {float(target)}, f"regime {regime_start}"


def test_changepoints_find_exactly_the_planted_regime_boundaries(meridian):
    shift = meridian.gt("shift")
    found = meridian.db.changepoints("degree", shift["entity"], shift["window"][0],
                                      shift["window"][1], shift["resolution_days"])
    assert found == shift["expected_changepoints"]


def test_native_changepoints_match_pure_python_on_a_real_signal(meridian):
    """The native binary-segmentation port is checked against pure Python on
    hand-written arrays elsewhere; this runs both over a signal actually
    produced by `TRACK` at full history depth, where the value sequence is
    long and not hand-chosen."""
    pytest.importorskip("coredb._native")
    deep = meridian.gt("deep_history")
    signal = meridian.db.track("degree", deep["entities"][0], "2021-01-04", "2025-12-29",
                                resolution_days=7)
    assert len(signal.points) > 200

    assert detect_changepoints(signal.points, use_native=True) == \
        detect_changepoints(signal.points, use_native=False)


