def test_shortest_path_hop_count_tracks_the_planted_chain(meridian):
    """The chain opens one edge at a time, breaks in the middle, heals, and
    is later short-circuited by a direct edge. Each sampled date has one
    correct hop count, fixed when the log was written."""
    chain = meridian.gt("chain")
    start, end = chain["nodes"][0], chain["nodes"][-1]

    for on_date, expected_hops in chain["path_at"]:
        path = meridian.db.path_exists(start, end, on_date, max_depth=4)
        actual = None if path is None else len(path)
        assert actual == expected_hops, f"on {on_date}"


def test_first_connected_finds_the_date_the_chain_completed(meridian):
    chain = meridian.gt("chain")
    window = chain["first_connected_window"]
    found = meridian.db.first_connected(chain["nodes"][0], chain["nodes"][-1],
                                         window[0], window[1], max_depth=4)
    assert found == chain["first_connected"]


def test_path_history_shows_the_chain_breaking_and_healing(meridian):
    """`PATH_HISTORY` over the break window must report disconnection while
    the middle edge is closed and reconnection after it reopens - the case a
    single `AS OF` probe cannot show. Stepping daily also pins the
    inclusive-`valid_to` boundary: the edge is open through its retract
    date, so connectivity survives that day and drops the next."""
    chain = meridian.gt("chain")
    break_start, break_end = chain["break"]
    points = meridian.db.path_history(chain["nodes"][0], chain["nodes"][-1],
                                       break_start, break_end, resolution_days=1, max_depth=4)
    connected = {p["date"]: p["path"] is not None for p in points}

    for on_date, expected in chain["break_boundary"]:
        assert connected[on_date] is expected, f"on {on_date}"

    # Between those boundaries nothing reconnects it - the shortcut that
    # could is not open until the following year.
    interior = [d for d in connected if break_start < d < break_end]
    assert interior and not any(connected[d] for d in interior)


def test_closeness_matches_the_planted_chain_geometry(meridian):
    """Harmonic closeness is `sum(1/distance)`, un-normalized, so a chain in
    its own component has an exactly predictable score - including how it
    changes when the shortcut pulls two nodes closer."""
    chain = meridian.gt("chain")
    for on_date, expected in chain["closeness_at"]:
        actual = meridian.db.closeness(chain["nodes"][0], on_date, max_depth=4)
        assert actual == pytest.approx(expected), f"on {on_date}"


def test_hub_degree_and_closeness_match_the_planted_fanout(meridian):
    """One node with a large planted fan-out, in its own component: degree
    is the peer count, and closeness is exactly that count too, since every
    peer sits at distance 1 and leads nowhere else."""
    hub = meridian.gt("hub")
    assert meridian.db.degree(hub["entity"], hub["on_date"]) == float(hub["degree"])
    assert meridian.db.closeness(hub["entity"], hub["on_date"], max_depth=4) == pytest.approx(
        float(hub["degree"]))


def test_dormant_entity_is_live_but_disconnected(meridian):
    """An entity whose only relationship closed years earlier still exists,
    but has no neighbours - degree and closeness must both be 0, not a stale
    value carried forward from when it was connected."""
    dormant = meridian.gt("dormant")
    opened, quiet = dormant["interval"][0], dormant["quiet_date"]

    assert meridian.db.degree(dormant["entity"], opened) == 1.0
    assert meridian.db.degree(dormant["entity"], quiet) == 0.0
    assert meridian.db.closeness(dormant["entity"], quiet, max_depth=4) == 0.0
    assert meridian.db.get_entity(dormant["entity"]) is not None


